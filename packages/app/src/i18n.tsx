export const messageCatalog: Record<Locale, Messages> = { 'zh-CN': zh, 'en-US': en };

export function systemLocale(): Locale {
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('en') ? 'en-US' : 'zh-CN';
}

interface I18nValue {
  locale: Locale;
  t: Messages;
  setLocale: (locale: Locale) => void;
}

const I18nContext = createContext<I18nValue>({ locale: 'zh-CN', t: zh, setLocale: () => undefined });

export function I18nProvider({ locale, onLocaleChange, children }: {
  locale: Locale;
  onLocaleChange: (locale: Locale) => void;
  children: ReactNode;
}) {
  useEffect(() => { document.documentElement.lang = locale; }, [locale]);
  const value = useMemo(() => ({ locale, t: messageCatalog[locale], setLocale: onLocaleChange }), [locale, onLocaleChange]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
